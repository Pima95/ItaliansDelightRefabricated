package dev.italiansdelight.integration.jei;

import dev.italiansdelight.ItaliansDelight;
import dev.italiansdelight.common.pizza.PizzaComposition;
import dev.italiansdelight.common.pizza.PizzaCreativeSamples;
import dev.italiansdelight.common.pizza.PizzaBaking;
import dev.italiansdelight.common.pizza.PizzaDisplayNames;
import dev.italiansdelight.common.pizza.PizzaItemData;
import dev.italiansdelight.common.pizza.PizzaQuarterSelection;
import dev.italiansdelight.common.pizza.PizzaToppingApplication;
import dev.italiansdelight.common.pizza.PizzaToppingCatalog;
import dev.italiansdelight.common.pizza.PizzaToppingType;
import dev.italiansdelight.common.registry.ModDataComponents;
import dev.italiansdelight.common.registry.ModItems;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Optional;
import java.util.Set;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;

/**
 * A small set of truthful JEI demonstrations of the existing dynamic recipe.
 *
 * <p>These previews use native, known items only; therefore they do not depend
 * on the server-side datapack-equivalence cache being populated on the client.
 * They never add actual crafting recipes or restrict other valid combinations.
 */
public final class PizzaCraftingJeiRecipes {
    private static final String DOUGH = "farmersdelight:wheat_dough";

    private PizzaCraftingJeiRecipes() {
    }

    public static List<PizzaCraftingJeiRecipe> createExamples() {
        List<PizzaCraftingJeiRecipe> examples = new ArrayList<>();
        // The result names are generated by PizzaDisplayNames, not hard-coded.
        addExample(examples, "farmersdelight:tomato_sauce"); // Rossa, one topping.
        addExample(examples, "farmersdelight:tomato_sauce",
                "italiansdelight:mozzarella_slice", "italiansdelight:basil"); // Margherita.
        addExample(examples, "italiansdelight:mozzarella_slice",
                "italiansdelight:gorgonzola_wedge",
                "italiansdelight:provolone_slice",
                "italiansdelight:grated_parmigiano_reggiano"); // Four cheeses.
        addExample(examples, "italiansdelight:mozzarella_slice",
                "italiansdelight:tomato_slice",
                "farmersdelight:cabbage_leaf",
                "farmersdelight:pumpkin_slice",
                "italiansdelight:basil"); // Five vegetable/dairy toppings.
        addExample(examples, "farmersdelight:tomato_sauce",
                "italiansdelight:mozzarella_slice", "italiansdelight:basil",
                "italiansdelight:tomato_slice", "farmersdelight:cooked_bacon",
                "italiansdelight:speck_slice"); // Six distinct topping kinds.
        // Every recognized flavor is discoverable in JEI. The plain Bianca
        // is not a shapeless recipe (dough alone is placed in the world);
        // JEI shows Bianca via baking and the Cutting Board instead.
        Set<String> shown = new HashSet<>();
        for (PizzaCraftingJeiRecipe example : examples) {
            PizzaItemData pizza = example.result().get(ModDataComponents.PIZZA_CONTENTS);
            if (pizza != null) {
                shown.add(PizzaDisplayNames.wholePresetId(pizza));
            }
        }
        for (var preset : PizzaDisplayNames.allPresets().entrySet()) {
            if (preset.getKey().isEmpty() || shown.contains(preset.getValue())) {
                continue;
            }
            // Native original source items and genuine full data, exactly as
            // in the already approved Creative sample catalogue.
            ItemStack raw = PizzaCreativeSamples.create(preset.getKey(), false);
            PizzaItemData data = raw.get(ModDataComponents.PIZZA_CONTENTS);
            var marked = data.composition().applications().stream()
                    .map(a -> PizzaBaking.isBowlBearing(a.canonicalId())
                            ? a.withCraftingBowlReturned() : a)
                    .toList();
            PizzaItemData crafted = new PizzaItemData(
                    data.composition().withApplications(marked, data.composition().nextApplicationId()),
                    data.legacyMozzarella());
            raw.set(ModDataComponents.PIZZA_CONTENTS, crafted);
            PizzaDisplayNames.nameWholeStack(raw, crafted);
            List<ItemStack> inputs = new ArrayList<>();
            inputs.add(stack(DOUGH).orElseThrow());
            marked.forEach(app -> inputs.add(app.originalStack()));
            examples.add(new PizzaCraftingJeiRecipe(inputs, raw));
            shown.add(preset.getValue());
        }
        return List.copyOf(examples);
    }

    private static void addExample(List<PizzaCraftingJeiRecipe> examples,
                                   String... toppingIds) {
        if (toppingIds.length < 1 || toppingIds.length > PizzaComposition.MAX_TOPPINGS_PER_QUARTER) {
            throw new IllegalArgumentException("JEI pizza preview must have 1-6 toppings");
        }

        Optional<ItemStack> dough = stack(DOUGH);
        if (dough.isEmpty()) {
            ItaliansDelight.LOGGER.warn("[Pizza / JEI] No Farmer's Delight dough; skipping preview");
            return;
        }

        List<ItemStack> ingredients = new ArrayList<>();
        ingredients.add(dough.get());
        List<PizzaToppingApplication> applications = new ArrayList<>();
        Set<Identifier> seen = new HashSet<>();
        boolean hasSauce = false;
        long sequence = 1L;

        for (String id : toppingIds) {
            Optional<ItemStack> candidate = stack(id);
            if (candidate.isEmpty()) {
                ItaliansDelight.LOGGER.warn("[Pizza / JEI] Missing sample ingredient {}; skipping preview", id);
                return;
            }
            ItemStack topping = candidate.get();
            Identifier itemId = BuiltInRegistries.ITEM.getKey(topping.getItem());
            PizzaToppingType type = PizzaToppingCatalog.findNativeItem(itemId).orElse(null);
            if (type == null || type.planned() || !seen.add(type.id())) {
                ItaliansDelight.LOGGER.warn("[Pizza / JEI] Invalid or duplicate sample ingredient {}; skipping preview", id);
                return;
            }
            if (type.occupiesSauceSlot()) {
                if (hasSauce) {
                    ItaliansDelight.LOGGER.warn("[Pizza / JEI] Multiple sauces in sample; skipping preview");
                    return;
                }
                hasSauce = true;
            }

            PizzaToppingApplication application = new PizzaToppingApplication(
                    sequence++, type.id(), topping,
                    PizzaQuarterSelection.ALL_QUARTERS,
                    PizzaQuarterSelection.ALL_QUARTERS
            );
            applications.add(PizzaBaking.isBowlBearing(type.id())
                    ? application.withCraftingBowlReturned() : application);
            ingredients.add(topping);
        }

        // Same four identical physical quarters and application chronology as
        // placing each ingredient once on an undivided pizza in the world.
        PizzaComposition composition = PizzaComposition.empty()
                .withApplications(applications, sequence);
        PizzaItemData data = new PizzaItemData(composition, false);
        ItemStack output = new ItemStack(ModItems.RAW_PIZZA);
        output.set(ModDataComponents.PIZZA_CONTENTS, data);
        PizzaDisplayNames.nameWholeStack(output, data);
        examples.add(new PizzaCraftingJeiRecipe(ingredients, output));
    }

    private static Optional<ItemStack> stack(String id) {
        return BuiltInRegistries.ITEM.getOptional(Identifier.parse(id))
                .map(ItemStack::new);
    }
}
